#!/usr/bin/env python3
"""Refresh embedded font subsets; optional authoring tool, never a site build step."""

import base64
import hashlib
import html
import io
from pathlib import Path
import re
from urllib.parse import quote
from urllib.request import urlopen

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / '.preview' / 'font-cache'
REVISION = '47d54ca1ebb14fd864695f1d39dc734f39017c33'
BASE_URL = f'https://raw.githubusercontent.com/google/fonts/{REVISION}/'
SOURCES = {
    'Inter.ttf': ('ofl/inter/Inter[opsz,wght].ttf', '29160a80ff49ddcab2c97711247e08b1fab27a484a329ce8b813d820dc559031'),
    'Inter-OFL.txt': ('ofl/inter/OFL.txt', '5b9321a4298cfeb6b34354164a1c3afc3db114569984c502b9b35d988fd58c57'),
    'NotoSansJP.ttf': ('ofl/notosansjp/NotoSansJP[wght].ttf', 'c2f3b4d463500a2ddcd3849cded1fceeb9fd6d1c32e6cbecd568453ba50fc68f'),
    'NotoSansJP-OFL.txt': ('ofl/notosansjp/OFL.txt', '1c05c68c34f9708415aada51f17e1b0092d2cea709bf4a94cd38114f9e73d7d9'),
}
FONT_START = '/* Embedded fonts: start */'
FONT_END = '/* Embedded fonts: end */'


def source_file(name):
    path, checksum = SOURCES[name]
    cached = CACHE / name
    if not cached.exists():
        with urlopen(BASE_URL + quote(path, safe='/'), timeout=60) as response:
            data = response.read()
    else:
        data = cached.read_bytes()
    if hashlib.sha256(data).hexdigest() != checksum:
        raise ValueError(f'Unexpected checksum for {name}')
    cached.write_bytes(data)
    return data


def strip_embedded_fonts(text):
    return re.sub(re.escape(FONT_START) + r'.*?' + re.escape(FONT_END), '', text, flags=re.S)


def font_face(family, data, codepoints):
    font = TTFont(io.BytesIO(data))
    cmap = font.getBestCmap()
    codepoints &= set(cmap)
    # Subset before axis instancing so the large Japanese source stays inexpensive.
    options = subset.Options()
    options.notdef_outline = True
    options.recalc_timestamp = False
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    instantiateVariableFont(font, {'wght': (400, 500)}, inplace=True)
    font.flavor = 'woff2'
    output = io.BytesIO()
    font.save(output)
    binary = output.getvalue()
    encoded = base64.b64encode(binary).decode('ascii')
    print(f'{family}: {len(codepoints)} codepoints, {len(binary):,} bytes WOFF2')
    return (
        f'    @font-face {{ font-family:"{family}"; font-style:normal; font-weight:400 500; '
        f'font-display:swap; src:url("data:font/woff2;base64,{encoded}") format("woff2"); }}'
    )


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    page_path, svg_path = ROOT / 'index.html', ROOT / 'ogp.svg'
    page, svg = strip_embedded_fonts(page_path.read_text()), strip_embedded_fonts(svg_path.read_text())
    # Exclude notices and code when collecting displayed characters.
    text = re.sub(r'<script\b[^>]*>.*?</script>|<style\b[^>]*>.*?</style>|<metadata\b[^>]*>.*?</metadata>|<!--.*?-->', '', page + svg, flags=re.S)
    used = {ord(character) for character in html.unescape(text)}
    latin = set(range(0x20, 0x250)) | set(range(0x2000, 0x2300))
    kana = set(range(0x3000, 0x3100)) | set(range(0xFF00, 0xFFF0))
    fonts = {name: source_file(name) for name in SOURCES}
    inter_cmap = set(TTFont(io.BytesIO(fonts['Inter.ttf'])).getBestCmap())
    japanese = (used - inter_cmap) | kana
    css = '\n'.join([
        FONT_START,
        font_face('Inter', fonts['Inter.ttf'], latin | (used & inter_cmap)),
        font_face('Noto Sans JP', fonts['NotoSansJP.ttf'], japanese),
        FONT_END,
    ])
    notices = '\n\n'.join([
        'Embedded font subsets, SIL Open Font License 1.1.\n'
        f'Source: https://github.com/google/fonts/tree/{REVISION}\n'
        'Generated by tools/embed-fonts.py. Original licenses follow.',
        'Inter\n' + fonts['Inter-OFL.txt'].decode(),
        'Noto Sans JP\n' + fonts['NotoSansJP-OFL.txt'].decode(),
    ])
    page = re.sub(r'\n?  <script type="text/plain" id="font-licenses">.*?</script>\n?', '\n', page, flags=re.S)
    page = page.replace('  <style>', f'  <script type="text/plain" id="font-licenses">\n{notices}\n  </script>\n  <style>\n    {css}', 1)
    svg = re.sub(r'\n?  <metadata id="font-licenses">.*?</metadata>\n?', '\n', svg, flags=re.S)
    svg = re.sub(r'\n?    <style><!\[CDATA\[\s*\]\]></style>\n?', '\n', svg, flags=re.S)
    svg = svg.replace('  <defs>', f'  <metadata id="font-licenses">{html.escape(notices)}</metadata>\n  <defs>\n    <style><![CDATA[\n{css}\n    ]]></style>', 1)
    page_path.write_text(page)
    svg_path.write_text(svg)
    print('Updated index.html and ogp.svg. Export ogp.svg as a 1200 × 630 PNG next.')


if __name__ == '__main__':
    main()
